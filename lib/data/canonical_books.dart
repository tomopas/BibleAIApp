/// Canonical book metadata used for navigation, plans and translation imports.
///
/// Chapter counts follow the KJV/Protestant canon for the 66 books; imported
/// bundles always use the chapter counts that are present in the source file.
class CanonicalBook {
  const CanonicalBook({
    required this.id,
    required this.name,
    required this.abbreviation,
    required this.testament,
    required this.order,
    required this.chapterCount,
    required this.scrollmapperName,
  });

  final String id;
  final String name;
  final String abbreviation;
  final String testament; // OT, NT, DC
  final int order;
  final int chapterCount;
  final String scrollmapperName;

  bool get isNewTestament => testament == 'NT';
  bool get isDeuterocanon => testament == 'DC';
}

